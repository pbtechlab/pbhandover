"use strict";

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { PACKAGE_ROOT, WORKER_ENV, TOOL_DIR } = require("../defaults");
const { readText, writeText } = require("../fs-utils");
const { resolveAgent, runExecutable } = require("../executables");
const { WORKER_PREFIX } = require("../cline-plugin");

const pluginFile = () => path.join(process.env.CLINE_DIR || path.join(os.homedir(), ".cline"), "plugins", "pbhandover.js");
const MARKER = "// Generated by pbhandover: Cline runtime integration";

module.exports = {
  name: "cline", defaultModel: null, lastMessageFile: "last-cline-message.txt", summaryFromStdout: true,
  isConfigured(root) { return fs.existsSync(path.join(root, ".cline")) || fs.existsSync(path.join(root, ".clinerules")); },
  isAvailable() { return Boolean(resolveAgent("cline")); },
  hookIgnoreEntry() { return null; },
  projectHookFileStatus() { const file = pluginFile(); return { path: file, exists: fs.existsSync(file) }; },
  enableStopHook() { this.installRouter({ quiet: true }); },
  disableStopHook() { /* The shared plugin checks each project's enabled state. */ },
  installRouter(options = {}) {
    const file = pluginFile();
    if (fs.existsSync(file) && !readText(file).startsWith(MARKER)) {
      throw new Error(`Refusing to replace an unrelated Cline plugin: ${file}`);
    }
    const moduleFile = path.join(PACKAGE_ROOT, "src", "cline-plugin.js");
    const settings = { node: process.execPath, entry: path.join(PACKAGE_ROOT, "bin", "pbhandover.js") };
    writeText(file, `${MARKER}\nmodule.exports = require(${JSON.stringify(moduleFile)}).createPlugin(${JSON.stringify(settings)});\n`);
    if (!options.quiet) console.log(`[cline] command router and completion hook: installed (${file})`);
  },
  uninstallRouter() {
    if (this.routerInstalled()) fs.unlinkSync(pluginFile());
  },
  routerInstalled() { return readText(pluginFile(), "").startsWith(MARKER); },
  routerStatusLines() { return [`[cline] plugin: ${pluginFile()}`, `[cline] router installed: ${this.routerInstalled()}`]; },
  runSummarizer({ root, model, prompt, timeout }) {
    // A short positional prompt avoids Windows stdin detection and command-line
    // length limits. The complete task stays in the project's private state.
    const promptFile = path.join(root, TOOL_DIR, "cline-prompt.md");
    writeText(promptFile, prompt);
    const args = ["--yolo", "--json", "--cwd", root];
    if (model) args.push("--model", model);
    args.push(WORKER_PREFIX + `Read the complete task instructions from ${JSON.stringify(promptFile)} and follow them. Update HANDOVER.md only, in place. Do not modify any other file.`);
    return runExecutable(resolveAgent("cline"), args, {
      cwd: root, timeout, maxBuffer: 10 * 1024 * 1024,
      env: { ...process.env, [WORKER_ENV]: "1" }
    });
  },
  normalizePayload(payload) {
    return {
      ...payload,
      cwd: payload.cwd || payload.workspaceRoots?.[0],
      prompt: payload.prompt || payload.userPromptSubmit?.prompt,
      session_id: payload.session_id || payload.taskId,
      hook_event_name: payload.hook_event_name || payload.hookName || "TaskComplete"
    };
  },
  formatRouterResponse(display, reason) {
    return JSON.stringify({ cancel: false, contextModification: [
      `${display} was handled locally by pbhandover.`,
      "Do not execute the original @handover command again or treat it as a new task.",
      "Reply only with a concise summary of this command result:", reason
    ].join("\n") });
  }
};
